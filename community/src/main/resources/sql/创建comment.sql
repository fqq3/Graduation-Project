
/*Table structure for table `comment` */

DROP TABLE IF EXISTS `comment`;

CREATE TABLE `comment` (
  `comment_id` bigint(20) NOT NULL COMMENT 'id',
  `create_by` varchar(32) DEFAULT NULL COMMENT '创建人者',
  `update_by` bigint(20) DEFAULT NULL COMMENT '更新者ID',
  `create_time` datetime DEFAULT NULL COMMENT '创建时间',
  `update_time` datetime DEFAULT NULL COMMENT '更新时间',
  `content` varchar(1024) DEFAULT NULL COMMENT '内容',
  `parent_id` bigint(20) DEFAULT '-1' COMMENT '父级ID',
  `del_flag` int(2) DEFAULT '0' COMMENT '删除状态0默认1删除',
  `interaction_id` bigint(20) DEFAULT NULL COMMENT '社区互动ID',
  `user_id` bigint(20) DEFAULT NULL COMMENT '创建人ID',
  `remark` varchar(255) DEFAULT NULL COMMENT '备注',
  `root_id` bigint(20) DEFAULT NULL COMMENT '划属Id',
  PRIMARY KEY (`comment_id`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 ROW_FORMAT=DYNAMIC COMMENT='评论表';

